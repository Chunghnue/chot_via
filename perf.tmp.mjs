import { chromium } from '@playwright/test';
const b = await chromium.launch({ channel: 'chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const p = await ctx.newPage();
const cdp = await ctx.newCDPSession(p);
await cdp.send('Network.enable'); await cdp.send('Network.emulateNetworkConditions', { offline: false, latency: 150, downloadThroughput: 1.6 * 1024 * 1024 / 8 * 4, uploadThroughput: 750 * 1024 / 8 });
let bytes = 0; const big = [];
p.on('response', async (r) => { try { const l = +(r.headers()['content-length'] ?? 0); bytes += l; if (l > 150000) big.push(`${Math.round(l / 1024)}KB ${r.url().split('/').slice(-2).join('/')}`); } catch {} });
const t0 = Date.now();
await p.goto(process.argv[2], { waitUntil: 'domcontentloaded', timeout: 120000 });
await p.locator('h1').first().waitFor();
const tH1 = Date.now() - t0;
await p.waitForLoadState('networkidle', { timeout: 120000 });
console.log('h1 visible ms', tH1, '| network idle ms', Date.now() - t0, '| total KB', Math.round(bytes / 1024));
console.log(big.slice(0, 10).join('\n'));
await b.close();
